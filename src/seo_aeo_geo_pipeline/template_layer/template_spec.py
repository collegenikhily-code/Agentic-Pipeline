@dataclass
class TemplateSpec:
    """Specification for a content generation template.

    A TemplateSpec describes:
    - The template name (used for lookup and rendering)
    - The template family/category (drives selection logic)
    - The prompt structure / sections
    - The output schema expected from the LLM call
    - Optional default parameter values
    """

    name: str
    family: str
    description: str
    prompt_sections: List[str]
    output_schema: List[str]
    default_params: Dict[str, Any] = field(default_factory=dict)
    priority: int = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "family": self.family,
            "description": self.description,
            "prompt_sections": self.prompt_sections,
            "output_schema": self.output_schema,
            "default_params": self.default_params,
            "priority": self.priority,
        }
